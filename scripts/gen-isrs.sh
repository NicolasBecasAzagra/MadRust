#!/bin/sh
# SPDX-License-Identifier: GPL-2.0-only
#
# Regenerate madrust-kernel/src/isrs.s from the vector table below.
#
# The table only lists the vectors for which the CPU pushes an error code.
# Every other stub pushes a zero error code so that the stack frame has the
# same layout for all 256 vectors.
#
# Vectors 32 to 47 are deliberately absent. Intel reserves them for software
# interrupts, which would push an error code, but MadRust remaps the 8259 PIC
# to 0x20-0x2F and hardware interrupts never push an error code. The kernel
# never executes an INT instruction with a vector in that range, so treating
# those vectors as "no error code" keeps the frame consistent for the only
# producer of them: the interrupt controller.

set -eu

cd "$(dirname "$0")/.."

OUT=madrust-kernel/src/isrs.s
ERROR_VECTORS="8 10 11 12 13 14 17 21 29 30"

{
    cat <<'HEADER'
/* SPDX-License-Identifier: GPL-2.0-only */
/*
 * Exception and IRQ stubs for MadRust.
 *
 * Generated by scripts/gen-isrs.sh; do not edit by hand.
 *
 * The CPU pushes RFLAGS, CS and RIP, plus an error code for the vectors listed
 * in the generator's ERROR_VECTORS table. Each stub pushes a dummy error code
 * when the CPU did not, then the vector number, and jumps to isr_common.
 * isr_common saves the general purpose registers, calls
 * madrust_interrupt_handler with a pointer to the InterruptFrame, restores the
 * frame and returns with iretq.
 */

    .section .text.isrs, "ax", @progbits
    .code64
HEADER

    vector=0
    while [ "$vector" -lt 256 ]; do
        case " $ERROR_VECTORS " in
            *" $vector "*)
                pushes_error=1
                ;;
            *)
                pushes_error=0
                ;;
        esac

        printf '\n'
        printf '    .global isr%d\n' "$vector"
        printf '    .type isr%d, @function\n' "$vector"
        printf 'isr%d:\n' "$vector"
        if [ "$pushes_error" -eq 0 ]; then
            printf '    pushq $0\n'
        fi
        printf '    pushq $%d\n' "$vector"
        printf '    jmp isr_common\n'

        vector=$((vector + 1))
    done

    cat <<'COMMON'

    .global isr_common
    .type isr_common, @function
isr_common:
    cld

    /* Save the interrupted context in the InterruptFrame layout. */
    pushq %rax
    pushq %rbx
    pushq %rcx
    pushq %rdx
    pushq %rsi
    pushq %rdi
    pushq %rbp
    pushq %r8
    pushq %r9
    pushq %r10
    pushq %r11
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15

    /*
     * The stub pushed the vector below the error code, but InterruptFrame
     * declares error_code first. Swap the two words so the handler sees the
     * documented layout. RAX is already saved in the frame, so it is free to
     * use as scratch. RIP at 136(%rsp) is not touched, and the return path
     * drops both words anyway.
     */
    movq 120(%rsp), %rax
    xchgq %rax, 128(%rsp)
    movq %rax, 120(%rsp)

    /*
     * RSP points at the InterruptFrame. RBP is callee-saved, so the C handler
     * preserves this frame pointer across the call. The stack is aligned
     * before the call because interrupts can arrive with any RSP alignment.
     */
    movq %rsp, %rdi
    movq %rsp, %rbp
    andq $-16, %rsp
    call madrust_interrupt_handler
    movq %rbp, %rsp

    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %r11
    popq %r10
    popq %r9
    popq %r8
    popq %rbp
    popq %rdi
    popq %rsi
    popq %rdx
    popq %rcx
    popq %rbx
    popq %rax

    /* Drop the vector number and the error code, then return to the
     * interrupted context. */
    addq $16, %rsp
    iretq

    .section .rodata.isr_table, "a", @progbits
    .balign 8
    .global isr_table
    .type isr_table, @object
isr_table:
COMMON

    vector=0
    while [ "$vector" -lt 256 ]; do
        printf '    .quad isr%d\n' "$vector"
        vector=$((vector + 1))
    done
} > "$OUT"
