const INITIAL: [u32; 8] = [
    0x6a09_e667,
    0xbb67_ae85,
    0x3c6e_f372,
    0xa54f_f53a,
    0x510e_527f,
    0x9b05_688c,
    0x1f83_d9ab,
    0x5be0_cd19,
];

/// SHA-256 of `bytes`.
pub fn digest(bytes: &[u8]) -> [u8; 32] {
    let mut state = INITIAL;
    let mut block = [0u8; 64];
    let mut offset = 0;
    while offset + 64 <= bytes.len() {
        block.copy_from_slice(&bytes[offset..offset + 64]);
        compress(&mut state, &block);
        offset += 64;
    }

    // The last block carries the remainder, a 0x80 byte, zero padding and the
    // bit length of the message, big endian.
    let remainder = bytes.len() - offset;
    block = [0u8; 64];
    block[..remainder].copy_from_slice(&bytes[offset..]);
    block[remainder] = 0x80;
    if remainder >= 56 {
        compress(&mut state, &block);
        block = [0u8; 64];
    }
    let bits = (bytes.len() as u64).wrapping_mul(8);
    block[56..].copy_from_slice(&bits.to_be_bytes());
    compress(&mut state, &block);

    let mut out = [0u8; 32];
    for (index, word) in state.iter().enumerate() {
        out[index * 4..index * 4 + 4].copy_from_slice(&word.to_be_bytes());
    }
    out
}

/// Lower case hexadecimal form of a digest.
pub fn hex(digest: &[u8; 32]) -> String {
    let mut out = String::with_capacity(64);
    for byte in digest {
        out.push(char::from_digit((byte >> 4) as u32, 16).unwrap_or('0'));
        out.push(char::from_digit((byte & 0x0f) as u32, 16).unwrap_or('0'));
    }
    out
}

fn compress(state: &mut [u32; 8], block: &[u8; 64]) {
    let mut words = [0u32; 64];
    for (index, word) in words.iter_mut().take(16).enumerate() {
        *word = u32::from_be_bytes([
            block[index * 4],
            block[index * 4 + 1],
            block[index * 4 + 2],
            block[index * 4 + 3],
        ]);
    }
    for index in 16..64 {
        let first = words[index - 15];
        let second = words[index - 2];
        let s0 = first.rotate_right(7) ^ first.rotate_right(18) ^ (first >> 3);
        let s1 = second.rotate_right(17) ^ second.rotate_right(19) ^ (second >> 10);
        words[index] = words[index - 16]
            .wrapping_add(s0)
            .wrapping_add(words[index - 7])
            .wrapping_add(s1);
    }

    let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut h] = *state;
    for index in 0..64 {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let choose = (e & f) ^ (!e & g);
        let temp1 = h
            .wrapping_add(s1)
            .wrapping_add(choose)
            .wrapping_add(K[index])
            .wrapping_add(words[index]);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let majority = (a & b) ^ (a & c) ^ (b & c);
        let temp2 = s0.wrapping_add(majority);
        h = g;
        g = f;
        f = e;
        e = d.wrapping_add(temp1);
        d = c;
        c = b;
        b = a;
        a = temp1.wrapping_add(temp2);
    }
    for (slot, value) in state.iter_mut().zip([a, b, c, d, e, f, g, h]) {
        *slot = slot.wrapping_add(value);
    }
}

#[cfg(test)]
mod tests {
    use super::{digest, hex};

    #[test]
    fn the_published_vectors_match() {
        assert_eq!(
            hex(&digest(b"")),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex(&digest(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex(&digest(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn a_message_longer_than_one_block_is_chained() {
        // The 112 byte message above spans two blocks: the length field sits in
        // a block of its own.
        let message = [b'a'; 112];
        assert_eq!(
            hex(&digest(&message)),
            "f54353008a2553262ecdc4a34749563ba0950e8b0fc8652780b0a614b99683c1"
        );
    }
}
