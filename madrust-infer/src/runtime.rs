//! The generation loop and the lines the serial log shows.
//!
//! The prompt is already encoded: the runtime does not implement a
//! pre-tokenizer. A model config may carry its own `prompt_ids`, which is what
//! the synthetic development model does; without that field the runtime uses
//! the baked reference prompt ids below. The prompt is never derived from the
//! text at run time.
//!
//! The first token is generated from the logits after the prompt. The time to
//! the first token covers the prefill of the prompt, that first sample, and the
//! `mlock` of the mapped weights: the pin faults every weight page in, so its
//! cost is honestly part of the first token. The log reports the pinned bytes
//! and the pin time separately. The tokens per second covers every token after
//! the first, including the forward pass that produced each one, so the two
//! numbers describe the same pipeline the comparison measures.
//!
//! Generation stops at `eos_token_id` or at the requested count, which is the
//! reference implementation's contract: the end of sequence token is part of
//! the generated list.
//!
//! [`generate_with`] optionally takes a byte grammar. The sample is then the
//! largest logit among the tokens the grammar allows, applied as whole tokens,
//! so the generated bytes stay inside the language. When no allowed token
//! remains, generation stops and the log names the reason: the call is either
//! complete or the grammar cannot continue. The plain [`generate`] path is the
//! unchanged greedy sample.
//!
//! The three files live at the initramfs root in the guest. A native run sets
//! `MADRUST_INFER_ROOT` to the directory that holds them, and the
//! `INFER root source=...` line says whether the root came from the
//! environment or from the guest. The environment is read once, before the
//! config, so a missing file names the path the run actually tried.
//!
//! [`Server`] is the shape a multi-step caller uses (the agent loop). It maps
//! and pins the weights once, then serves every prompt from the same mapping.
//! The older one-shot entry points stay available: [`generate_from`] is now a
//! one-shot server, so its output is the output it always had.

