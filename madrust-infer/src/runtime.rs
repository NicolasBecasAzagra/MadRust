/// The guest paths, remapped through [`crate::paths`] when the host sets
/// `MADRUST_INFER_ROOT`.
pub use crate::paths::{CONFIG_PATH, MODEL_PATH, VOCAB_PATH};

/// Reference prompt ids for `The capital of France is`, from the SmolLM2-135M
/// tokenizer. Used when the config has no `prompt_ids` field.
pub use crate::reference::PROMPT_IDS as BAKED_PROMPT_IDS;

/// What one generation run produced.
pub struct Generation {
    /// Generated token ids, in order, including an end of sequence token.
    pub tokens: Vec<u32>,
    /// Decoded bytes of those ids.
    pub bytes: Vec<u8>,
    /// Decoded prompt followed by the generated bytes.
    pub full_bytes: Vec<u8>,
    /// Time to the first token.
    ///
    /// A one-shot run measures from before the pin, so this includes the cost
    /// of the promise. A [`Server`] pins once at open and its steps start
    /// after that, so a step reports only the prompt and the sample.
    pub first_token: Duration,
    /// Tokens per second after the first token.
    pub tokens_per_second: f64,
    /// Multiply accumulates the generation performed.
    pub matmul_macs: u64,
    /// Time spent inside the matrix vector products.
    pub matmul_seconds: f64,
    /// Rate of those products, in multiply accumulates per second.
    pub matmul_macs_per_second: f64,
    /// Twice the rate, the usual floating point operations per second.
    pub matmul_flops_per_second: f64,
    /// `true` when generation stopped on the end of sequence token.
    pub eos_reached: bool,
    /// `true` when a grammar was given and the generation stopped because
    /// the grammar had nothing more to say: either no token was allowed, or
    /// the call was already complete.
    pub grammar_stopped: bool,
    /// Characters of the vocabulary strings that were outside the byte-level
    /// alphabet and were written as their own UTF-8 bytes.
    pub outside_alphabet: usize,
    /// `true` when the decoded bytes are valid UTF-8.
    pub valid_utf8: bool,
    /// `true` when the prompt plus generated bytes are valid UTF-8.
    pub full_valid_utf8: bool,
    /// Golden tokens: the config's `expected_tokens`, or the published
    /// reference values when the checkpoint is the reference model.
    pub expected: Option<Vec<u32>>,
}

/// Read a file in bounded chunks.
///
/// The buffer is a stack array, not a large `Vec`: MadRust's `read` checks that
/// every destination page is already present, and a freshly allocated large
/// buffer may still be demand-paged. Writing into the heap happens in user mode
/// after the system call, where a fault is handled normally.
fn read_stream(mut file: std::fs::File) -> Result<Vec<u8>> {
    let size = usize::try_from(file.metadata()?.len())
        .map_err(|_| Error::new("runtime: file is too large for this target"))?;
    let mut bytes = Vec::with_capacity(size);
    let mut buffer = [0u8; 4096];
    loop {
        let count = file.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        bytes.extend_from_slice(&buffer[..count]);
    }
    Ok(bytes)
}

/// Read a small file from the initramfs into memory.
fn read_file(path: &str) -> Result<Vec<u8>> {
    read_stream(open_readonly(path)?)
}

/// Read an optional file, reporting an absent one as `None`.
fn read_optional(path: &str) -> Result<Option<Vec<u8>>> {
    match open_readonly_optional(path)? {
        Some(file) => Ok(Some(read_stream(file)?)),
        None => Ok(None),
    }
}

/// Load the config and say where every value came from.
fn load_config(path: &str) -> Result<Config> {
    match read_optional(path)? {
        Some(bytes) => {
            println!("INFER config={path}");
            Config::parse(&bytes)
        }
        None => {
            println!("INFER config={path} missing, using defaults");
            Ok(Config::defaults())
        }
    }
}

/// Generate up to `count` tokens, using the prompt from the config or the baked
/// reference prompt.
pub fn generate(count: usize) -> Result<Generation> {
    generate_with(count, None)
}

/// Generate up to `count` tokens, optionally constrained by a byte grammar.
///
/// With `Some(grammar)` the sample is the argmax over the tokens the grammar
/// allows at the current state. The whole byte sequence of a token is applied
/// before it is accepted. When the allowed set is empty generation stops and
/// [`Generation::grammar_stopped`] is set; a complete tool call ends that way
/// because the grammar has no byte after it.
pub fn generate_with(count: usize, grammar: Option<&Grammar>) -> Result<Generation> {
    if count == 0 {
        return Err(Error::new("runtime: nothing to generate"));
    }
    let (paths, root_source) = resolve()?;
    println!("INFER root source={} path={}", root_source, paths.root);
    let config = load_config(&paths.config)?;
    let (prompt, source) = match config.prompt_ids.as_deref() {
        Some(ids) => (ids, "config"),
        None => (BAKED_PROMPT_IDS.as_slice(), "baked"),
    };
    generate_with_prompt(prompt, source, count, &config, &paths, grammar)
}

/// Generate from a prompt the caller built, optionally constrained by a
/// grammar.
///
/// The prompt is a list of token ids, so a caller that builds a conversation
/// at run time (the agent loop) can serve the model without a pre-tokenizer
/// in the runtime. The rest of the pipeline is the one [`generate_with`] uses:
/// the same model, the same timing and the same log lines.
///
/// The call is a one-shot [`Server`]: the model is mapped and pinned for this
/// one request, exactly as it was before the server existed. The pin is
/// reported after the prompt line, so the serial log keeps the shape a
/// single-step run has always had.
pub fn generate_from(
    prompt: &[u32],
    count: usize,
    grammar: Option<&Grammar>,
) -> Result<Generation> {
    if count == 0 {
        return Err(Error::new("runtime: nothing to generate"));
    }
    let mut server = Server::open_inner(false)?;
    server.generate_inner(prompt, count, grammar, true)
}

/// A runtime that keeps the model mapped and pinned between calls.
///
/// The agent asks the model several times with different prompts. Loading and
/// pinning the weights once per step would charge the mapping, the tensor
/// directory and the `mlock` to every step, so the server keeps them for the
/// whole run. The log reports the pin once, when [`Server::open`] returns.
pub struct Server {
    // `Model` borrows the mapped file, and every borrow has to stay valid for
    // the whole run. The process is short lived, so the file is leaked instead
    // of building a self-referential struct: the leak is the lifetime the
    // borrow asks for, and the mapping stays alive until the process leaves.
    _file: &'static ModelFile,
    config: Config,
    vocab: Vocab,
    model: Model<'static>,
    pinned: core::result::Result<usize, i64>,
    pin_seconds: f64,
    pin_reported: bool,
}

impl Server {
    /// Open the model, map the weights and pin them once.
    ///
    /// The pin faults every weight page in, so it is the expensive part of the
    /// first request and belongs to the open, not to a step. The log reports
    /// the pinned bytes and the pin time here and nowhere else.
    pub fn open() -> Result<Self> {
        Self::open_inner(true)
    }

    /// Generate from a prompt the caller built, with an optional grammar.
    ///
    /// The prompt is already encoded; [`Server::vocab`] is what an encoder
    /// needs to build one. The log of a step names the prompt length and the
    /// time the step took.
    pub fn generate(
        &mut self,
        prompt: &[u32],
        count: usize,
        grammar: Option<&Grammar>,
    ) -> Result<Generation> {
        self.generate_inner(prompt, count, grammar, false)
    }

    /// The vocabulary of the model, for the caller that encodes prompts.
    pub fn vocab(&self) -> &Vocab {
        &self.vocab
    }

    /// The shared open path. `report_pin` is false only for the one-shot
    /// wrapper in [`generate_from`], which keeps the historical order of the
    /// prompt and pin lines.
    fn open_inner(report_pin: bool) -> Result<Self> {
        let (paths, root_source) = resolve()?;
        println!("INFER root source={} path={}", root_source, paths.root);
        let config = load_config(&paths.config)?;
        let file = Box::leak(Box::new(ModelFile::open(&paths.model)?));
        let vocab = {
            let bytes = read_file(&paths.vocab)?;
            Vocab::parse(&bytes)?
        };
        let model = Model::new(file, &config)?;
        let dims = model.dims();
        if !vocab.covers(dims.vocab) {
            return Err(Error::new(format!(
                "runtime: vocab.json does not cover the {} ids the model expects",
                dims.vocab
            )));
        }

        println!(
            "INFER model={} weights={} tensors={}",
            paths.model,
            model.weight_dtype(),
            model.tensor_count()
        );
        println!(
            "INFER map huge={} bytes={}",
            file.huge_pages_requested(),
            file.mapped_len()
        );
        println!("INFER source {}", config.provenance());
        println!("INFER matmul kernel={}", matvec::kernel_name());
        println!(
            "INFER dims hidden={} layers={} q_heads={} kv_heads={} head_dim={} ffn={} vocab={} eps={} rope_theta={} rope={} tie={} eos={}",
            dims.hidden,
            dims.layers,
            dims.q_heads,
            dims.kv_heads,
            dims.head_dim,
            dims.ffn,
            dims.vocab,
            dims.eps,
            dims.rope_theta,
            if dims.rope_interleaved {
                "interleaved"
            } else {
                "split-half"
            },
            dims.tie_word_embeddings,
            dims.eos_token_id
        );

        let start = Instant::now();
        let pinned = file.pin();
        let pin_seconds = start.elapsed().as_secs_f64();
        let mut server = Self {
            _file: file,
            config,
            vocab,
            model,
            pinned,
            pin_seconds,
            pin_reported: false,
        };
        if report_pin {
            server.report_pin();
        }
        Ok(server)
    }

    /// Print the pin line once and remember that it was printed.
    fn report_pin(&mut self) {
        match self.pinned {
            Ok(bytes) => println!(
                "INFER pinned bytes={bytes} ms={:.3}",
                self.pin_seconds * 1000.0
            ),
            Err(error) => println!(
                "INFER pinned bytes=0 error={error} ms={:.3}",
                self.pin_seconds * 1000.0
            ),
        }
        self.pin_reported = true;
    }

    /// Serve one prompt. `legacy` keeps the one-shot log free of the step line.
    fn generate_inner(
        &mut self,
        prompt: &[u32],
        count: usize,
        grammar: Option<&Grammar>,
        legacy: bool,
    ) -> Result<Generation> {
        if count == 0 {
            return Err(Error::new("runtime: nothing to generate"));
        }
        if prompt.is_empty() {
            return Err(Error::new("runtime: the prompt is empty"));
        }
        println!("INFER prompt={} tokens source=caller", prompt.len());
        // The one-shot server has not reported the pin yet, and the historical
        // timing charges it to the first token. The long-lived server reported
        // it at open, so a step starts after the pin.
        let start = Instant::now();
        if !self.pin_reported {
            self.report_pin();
        }
        let generation = generate_session(
            prompt,
            count,
            grammar,
            &self.config,
            &self.vocab,
            &self.model,
            start,
        )?;
        if !legacy {
            println!(
                "INFER step prompt={} tokens source=caller ms={:.3}",
                prompt.len(),
                start.elapsed().as_secs_f64() * 1000.0
            );
        }
        Ok(generation)
    }
}

fn generate_with_prompt(
    prompt: &[u32],
    prompt_source: &str,
    count: usize,
    config: &Config,
    paths: &Paths,
    grammar: Option<&Grammar>,
) -> Result<Generation> {
    if prompt.is_empty() {
        return Err(Error::new("runtime: the prompt is empty"));
    }

    let file = ModelFile::open(&paths.model)?;
    let vocab = {
        let bytes = read_file(&paths.vocab)?;
        Vocab::parse(&bytes)?
    };
    let model = Model::new(&file, config)?;
    let dims = model.dims();
    if !vocab.covers(dims.vocab) {
        return Err(Error::new(format!(
            "runtime: vocab.json does not cover the {} ids the model expects",
            dims.vocab
        )));
    }

    println!(
        "INFER model={} weights={} tensors={}",
        paths.model,
        model.weight_dtype(),
        model.tensor_count()
    );
    println!(
        "INFER map huge={} bytes={}",
        file.huge_pages_requested(),
        file.mapped_len()
    );
    println!("INFER source {}", config.provenance());
    println!("INFER matmul kernel={}", matvec::kernel_name());
    println!(
        "INFER dims hidden={} layers={} q_heads={} kv_heads={} head_dim={} ffn={} vocab={} eps={} rope_theta={} rope={} tie={} eos={}",
        dims.hidden,
        dims.layers,
        dims.q_heads,
        dims.kv_heads,
        dims.head_dim,
        dims.ffn,
        dims.vocab,
        dims.eps,
        dims.rope_theta,
        if dims.rope_interleaved {
            "interleaved"
        } else {
            "split-half"
        },
        dims.tie_word_embeddings,
        dims.eos_token_id
    );
    println!(
        "INFER prompt={} tokens source={}",
        prompt.len(),
        prompt_source
    );

    // The pin happens after the mapping exists and before the first forward,
    // and it is inside the first token measurement because `mlock` faults the
    // weights in: the cost of the promise is part of the first token.
    let start = Instant::now();
    let pinned = file.pin();
    let pin_seconds = start.elapsed().as_secs_f64();
    match pinned {
        Ok(bytes) => println!("INFER pinned bytes={bytes} ms={:.3}", pin_seconds * 1000.0),
        Err(error) => println!(
            "INFER pinned bytes=0 error={error} ms={:.3}",
            pin_seconds * 1000.0
        ),
    }
    generate_session(prompt, count, grammar, config, &vocab, &model, start)
}

/// Run the prompt and the sampled tokens through one session.
///
/// `start` is the instant the caller wants the timings measured from. A
/// one-shot run passes the instant before the pin, so the first token still
/// includes the promise; a server passes the instant after its pin, because
/// the pin belongs to the open.
fn generate_session(
    prompt: &[u32],
    count: usize,
    grammar: Option<&Grammar>,
    config: &Config,
    vocab: &Vocab,
    model: &Model<'_>,
    start: Instant,
) -> Result<Generation> {
    let capacity = prompt
        .len()
        .checked_add(count)
        .ok_or_else(|| Error::new("runtime: context length overflow"))?;
    let mut session = model.session(capacity)?;
    let dims = model.dims();
    for &token in prompt {
        session.forward(token)?;
    }
    let mut state = grammar.map(Grammar::start);
    let mut grammar_stopped = false;
    let mut tokens = Vec::with_capacity(count);
    let mut eos_reached = false;

    let first = match grammar {
        Some(active) => {
            let current = state.ok_or_else(|| Error::new("runtime: grammar state is missing"))?;
            let allowed = active.allowed_tokens(current, vocab);
            if allowed.is_empty() {
                grammar_stopped = true;
                None
            } else {
                let token = sample_allowed(session.logits(), &allowed)?;
                state = Some(advance_token(active, current, token, vocab)?);
                Some(token)
            }
        }
        None => Some(session.sample()?),
    };
    if let Some(token) = first {
        eos_reached = token == dims.eos_token_id;
        tokens.push(token);
    }
    let first_token = start.elapsed();

    while tokens.len() < count && !eos_reached && !grammar_stopped {
        let token = *tokens
            .last()
            .ok_or_else(|| Error::new("runtime: the token list is empty"))?;
        session.forward(token)?;
        let next = match grammar {
            Some(active) => {
                let current =
                    state.ok_or_else(|| Error::new("runtime: grammar state is missing"))?;
                let allowed = active.allowed_tokens(current, vocab);
                if allowed.is_empty() {
                    grammar_stopped = true;
                    break;
                }
                let next = sample_allowed(session.logits(), &allowed)?;
                let next_state = advance_token(active, current, next, vocab)?;
                // The call is complete: the grammar says so, and a model that
                // keeps writing after it has closed the call is writing
                // something the caller cannot use. The generation stops here.
                state = Some(next_state);
                if active.is_complete(next_state) {
                    grammar_stopped = true;
                }
                next
            }
            None => session.sample()?,
        };
        eos_reached = next == dims.eos_token_id;
        tokens.push(next);
    }
    let total = start.elapsed();

    let stop_reason = if grammar_stopped {
        "grammar"
    } else if eos_reached {
        "eos"
    } else {
        "count"
    };
    if grammar.is_some() {
        println!(
            "INFER grammar stopped={} reason={} tokens={}",
            grammar_stopped,
            stop_reason,
            tokens.len()
        );
    }

    let decode = total.saturating_sub(first_token).as_secs_f64();
    let generated_after_first = tokens.len().saturating_sub(1);
    let tokens_per_second = if generated_after_first > 0 && decode > 0.0 && decode.is_finite() {
        generated_after_first as f64 / decode
    } else {
        0.0
    };
    let matmul_seconds = session.matmul_nanos() as f64 / 1_000_000_000.0;
    let matmul_macs = session.matmul_macs();
    let (matmul_macs_per_second, matmul_flops_per_second) = if matmul_seconds > 0.0 {
        let rate = matmul_macs as f64 / matmul_seconds;
        (rate, 2.0 * rate)
    } else {
        (0.0, 0.0)
    };
    let expected = config.expected_tokens.clone().or_else(|| {
        if is_reference_model(&dims)
            && prompt == reference::PROMPT_IDS
            && count >= reference::NEW_TOKENS.len()
        {
            Some(reference::NEW_TOKENS.to_vec())
        } else {
            None
        }
    });
    let decoded = vocab.decode(&tokens)?;
    let mut full_bytes = vocab.decode(prompt)?.bytes;
    full_bytes.extend_from_slice(&decoded.bytes);

    Ok(Generation {
        tokens,
        valid_utf8: core::str::from_utf8(&decoded.bytes).is_ok(),
        full_valid_utf8: core::str::from_utf8(&full_bytes).is_ok(),
        bytes: decoded.bytes,
        full_bytes,
        outside_alphabet: decoded.outside_alphabet,
        first_token,
        tokens_per_second,
        matmul_macs,
        matmul_seconds,
        matmul_macs_per_second,
        matmul_flops_per_second,
        eos_reached,
        grammar_stopped,
        expected,
    })
}

/// Pick the largest logit among `allowed`.
fn sample_allowed(logits: &[f32], allowed: &[u32]) -> Result<u32> {
    let mut best: Option<(u32, f32)> = None;
    for &token in allowed {
        let value = *logits
            .get(token as usize)
            .ok_or_else(|| Error::new(format!("runtime: allowed token {token} has no logit")))?;
        if best.is_none_or(|(_, maximum)| value > maximum) {
            best = Some((token, value));
        }
    }
    best.map(|(token, _)| token)
        .ok_or_else(|| Error::new("runtime: no allowed token to sample"))
}

/// Move a grammar state over the whole byte sequence of one token.
fn advance_token(grammar: &Grammar, state: State, token: u32, vocab: &Vocab) -> Result<State> {
    let mut bytes = Vec::new();
    if !vocab.token_bytes_into(token, &mut bytes) {
        return Err(Error::new(format!(
            "runtime: token {token} has no byte representation"
        )));
    }
    grammar
        .advance(state, &bytes)
        .ok_or_else(|| Error::new(format!("runtime: grammar rejected token {token}")))
}

/// `true` when the dimensions are those of the published SmolLM2-135M run.
///
/// The token gate is keyed on the whole shape, not on the file name, because
/// the runtime never reads a model name. A checkpoint with the same shape is
/// the same arithmetic in the same order, which is what the comparison covers.
fn is_reference_model(dims: &Dims) -> bool {
    dims.hidden == 576
        && dims.layers == 30
        && dims.q_heads == 9
        && dims.kv_heads == 3
        && dims.head_dim == 64
        && dims.ffn == 1536
        && dims.vocab == 49_152
        && dims.tie_word_embeddings
        && dims.eos_token_id == 0
}

/// Print the result lines.
pub fn print(generation: &Generation) {
    let tokens: Vec<String> = generation
        .tokens
        .iter()
        .map(|token| token.to_string())
        .collect();
    println!("INFER tokens {}", tokens.join(" "));
    println!("INFER text {}", String::from_utf8_lossy(&generation.bytes));
    println!(
        "INFER full_text {}",
        String::from_utf8_lossy(&generation.full_bytes)
    );
    println!(
        "INFER decode alphabet=byte-level outside_alphabet={} utf8={} full_utf8={}",
        generation.outside_alphabet,
        if generation.valid_utf8 {
            "valid"
        } else {
            "lossy"
        },
        if generation.full_valid_utf8 {
            "valid"
        } else {
            "lossy"
        }
    );
    println!("INFER eos_reached={}", generation.eos_reached);
    println!(
        "INFER ttft_ms {:.3}",
        generation.first_token.as_secs_f64() * 1000.0
    );
    println!("INFER tok_per_s {:.3}", generation.tokens_per_second);
    println!(
        "INFER matmul macc={} flops={} seconds={:.3} macc_per_s={:.0} flops_per_s={:.0}",
        generation.matmul_macs,
        generation.matmul_macs.saturating_mul(2),
        generation.matmul_seconds,
        generation.matmul_macs_per_second,
        generation.matmul_flops_per_second
    );
}

/// Join token ids for the log.
fn ids(ids: &[u32]) -> String {
    ids.iter().map(u32::to_string).collect::<Vec<_>>().join(" ")
}

/// Run one generation, print the log lines and check the golden value.
pub fn run(count: usize) -> Result<()> {
    let generation = generate(count)?;
    print(&generation);
    if let Some(expected) = &generation.expected {
        // A native run may ask for more tokens than the reference list holds,
        // so the reference is the prefix the published run covers.
        let matches = generation.tokens.len() >= expected.len()
            && generation.tokens[..expected.len()] == expected[..];
        println!(
            "INFER golden expected={} actual={} match={}",
            ids(expected),
            ids(&generation.tokens),
            matches
        );
        if !matches {
            return Err(Error::new(
                "runtime: generated tokens differ from the reference",
            ));
        }
    }
    println!("INFER OK");
    Ok(())
}

